//! Sway settings from the Settings app: `~/.config/sway/settings.conf`, which the main config
//! includes last (`include`), so it overrides the defaults. A line's key is the start of the command
//! (e.g. `output eDP-1 scale` or `input type:touchpad tap`). A change is saved and sent to the
//! running Sway right away.

use crate::common::home;

fn file() -> std::path::PathBuf {
    home().join(".config/sway/settings.conf")
}

const HEADER: &str = "# Generated by the Settings app (apogee settings); manual edits are overwritten.
# Included at the end of ~/.config/sway/config.
";

fn rows() -> Vec<String> {
    std::fs::read_to_string(file())
        .unwrap_or_default()
        .lines()
        .filter(|r| !r.starts_with('#') && !r.trim().is_empty())
        .map(String::from)
        .collect()
}

fn is_key(row: &str, key: &str) -> bool {
    row.starts_with(key) && row[key.len()..].starts_with(' ')
}

fn write(rows: &[String]) {
    let _ = std::fs::write(file(), format!("{HEADER}{}\n", rows.join("\n")));
}

/// The saved value (the line without the key), if Settings ever set it.
pub fn value(key: &str) -> Option<String> {
    rows().iter().find(|r| is_key(r, key)).map(|r| r[key.len()..].trim().to_string())
}

/// Saves `key value` (replaces the old line), sends nothing to Sway.
pub fn save(key: &str, value: &str) {
    let mut r: Vec<String> = rows().into_iter().filter(|r| !is_key(r, key)).collect();
    r.push(format!("{key} {value}"));
    write(&r);
}

/// Saves `key value` and sends it to Sway.
pub fn set(key: &str, value: &str) {
    save(key, value);
    crate::sway::command(&format!("{key} {value}"));
}
